export function translate(lang: Lang, key: TranslationKey): string {
  return translations[lang][key] ?? translations.en[key] ?? key;
}

export function getVenueName(venue: { name: string; name_ka: string | null; name_ru: string | null }, lang: Lang): string {
  if (lang === 'ka' && venue.name_ka) return venue.name_ka;
  if (lang === 'ru' && venue.name_ru) return venue.name_ru;
  return venue.name;
}

export function getVenueDescription(venue: { description: string | null; description_ka: string | null; description_ru: string | null }, lang: Lang): string {
  if (lang === 'ka' && venue.description_ka) return venue.description_ka;
  if (lang === 'ru' && venue.description_ru) return venue.description_ru;
  return venue.description ?? '';
}

